function offlineTranslatedMeaning(value, language) {
  try {
    const numMap = (typeof window !== 'undefined' && window.NEPALI_NUMBER_MAP) || {};
    const allDict = (typeof window !== 'undefined' && window.OFFLINE_MEANING_WORD_MAP) || {};
    if (typeof value !== 'string' || !value.trim()) return value;
    if (!language || language === 'en') return value;
    const dict = allDict[language] || {};
    if (language === 'ne') {
      const full = value.trim().toLowerCase();
      if (numMap[full]) return numMap[full];
    }
    const splitter = new RegExp('([,;\\/()_\\u00b7\\u2022\\s]+)', 'g');
    const isDelimiter = new RegExp('^[,;\\/()_\\u00b7\\u2022\\s]+$');
    return value.split(splitter).map((token) => {
      if (!token || isDelimiter.test(token)) return token;
      const lower = token.toLowerCase();
      if (dict[lower]) return dict[lower];
      if (language === 'ne' && numMap[lower]) return numMap[lower];
      return token;
    }).join('');
  } catch (error) {
    return value;
  }
}
